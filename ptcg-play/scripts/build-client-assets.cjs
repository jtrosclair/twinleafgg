// Build-time only: publish the executable library's metadata as static assets.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const play = path.resolve(__dirname, '..');
const server = path.resolve(play, '../ptcg-server');
const { ensureClientCards } = require(path.join(server, 'browser/client/cards'));
const { CARD_LIBRARY_SCHEMA_VERSION, compactCardImageReference, isCardImageReference } = require(path.join(server, 'browser/client/card-metadata'));

function filesIn(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap(entry => entry.isDirectory() ? filesIn(path.join(directory, entry.name)) : [path.join(directory, entry.name)]);
}

const cards = ensureClientCards();
const imageMapFile = path.join(server, 'data/limitlesstcg-images.json');
const imageMap = JSON.parse(fs.readFileSync(imageMapFile, 'utf8'));
// Both compiled formats use this registration order. The generated frontend
// constants and metadata pin its SHA-256 identity without a runtime crypto job.
const catalogueHash = crypto.createHash('sha256').update(JSON.stringify(cards.map(card => card.fullName))).digest('hex');
const images = cards.map(card => compactCardImageReference(
  imageMap[card.usSetNumber || `${card.set} ${card.setNumber}`] || card.cardImage));
if (images.some(image => !isCardImageReference(image))) {
  throw new Error('The card catalogue contains an invalid image reference.');
}
// A rule/effect fix must invalidate the library even when its card text is unchanged.
const digest = crypto.createHash('sha256');
digest.update(`card-metadata-schema:${CARD_LIBRARY_SCHEMA_VERSION}\0`);
digest.update(`catalogue-order:${catalogueHash}\0`);
digest.update(fs.readFileSync(imageMapFile));
const source = path.join(server, 'src');
const engineFiles = ['game', 'sets', 'client', 'utils', 'simple-bot']
  .flatMap(directory => filesIn(path.join(source, directory)))
  .concat(['browser.ts', 'index.ts'].map(file => path.join(source, file)))
  .filter(file => file.endsWith('.ts') && !file.endsWith('.spec.ts') && !file.endsWith('.d.ts')
    && !path.relative(source, file).split(path.sep).some(part => ['tests', '__tests__'].includes(part)))
  .sort();
for (const file of engineFiles) {
  digest.update(path.relative(source, file).split(path.sep).join('/'));
  digest.update('\0');
  digest.update(fs.readFileSync(file));
  digest.update('\0');
}
const hash = digest.digest('hex');
const target = path.join(play, 'src/assets/simulator');
fs.mkdirSync(target, { recursive: true });
for (const file of fs.readdirSync(target).filter(file => /^cards\..*\.json$/.test(file))) {
  fs.unlinkSync(path.join(target, file));
}
fs.writeFileSync(path.join(target, `cards.${hash}.json`), JSON.stringify({ ok: true,
  cardsInfo: { schemaVersion: CARD_LIBRARY_SCHEMA_VERSION, images, hash, catalogueHash } }));
fs.writeFileSync(path.join(target, 'cards.hash.json'), JSON.stringify({ ok: true,
  schemaVersion: CARD_LIBRARY_SCHEMA_VERSION, hash, catalogueHash, cardsTotal: images.length }));
fs.writeFileSync(path.join(play, 'src/app/client-library-version.ts'), `// Generated by scripts/build-client-assets.cjs.\nexport const CLIENT_LIBRARY_HASH = '${hash}';\nexport const CLIENT_CATALOGUE_HASH = '${catalogueHash}';\nexport const CLIENT_CARD_TOTAL = ${images.length};\n`);
console.log(`Static simulator metadata v${CARD_LIBRARY_SCHEMA_VERSION}: ${images.length} executable card images, ${hash.slice(0, 12)}`);

const { collectResources, bootstrap } = require('./static-resources.cjs');
fs.writeFileSync(path.join(play, 'src/simulator-static.js'), bootstrap(collectResources(path.join(play, 'src'))));
